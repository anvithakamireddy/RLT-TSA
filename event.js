// Builds the picture carousel for an event. Only events that have examples get one,
// and videos that are already listed under Example Projects are skipped.
function buildGallery(slug, event) {
    const section = document.getElementById("event-gallery-section");
    const track = document.getElementById("gallery-track");
    const dots = document.getElementById("gallery-dots");
    const counter = document.getElementById("gallery-counter");
    const prev = document.getElementById("gallery-prev");
    const next = document.getElementById("gallery-next");
    if (!section || !track) return;

    const examples = (event && event.examples) || [];
    if (!examples.length) {
        section.hidden = true;
        return;
    }

    const exampleUrls = examples.map(example => example.url).join(" ");
    const slides = [];

    (eventWinnerPhotos[slug] || []).forEach(photo => {
        slides.push(makeSlide({
            image: photo.image,
            alt: photo.caption,
            title: photo.caption,
            credit: textLink("Photo: Washington TSA ↗", photo.page)
        }));
    });

    (eventGallery[slug] || [])
        .filter(v => !exampleUrls.includes(v.id))
        .forEach(v => {
            slides.push(makeSlide({
                image: `https://i.ytimg.com/vi/${v.id}/hqdefault.jpg`,
                alt: `Video thumbnail: ${v.title}`,
                title: v.title,
                credit: v.channel,
                href: `https://www.youtube.com/watch?v=${v.id}`
            }));
        });

    if (!slides.length) {
        section.hidden = true;
        return;
    }

    track.innerHTML = "";
    dots.innerHTML = "";
    slides.forEach((slide, i) => {
        slide.setAttribute("aria-label", `${i + 1} of ${slides.length}`);
        track.appendChild(slide);

        const dot = document.createElement("button");
        dot.type = "button";
        dot.className = "gallery-dot";
        dot.setAttribute("aria-label", `Go to slide ${i + 1}`);
        dot.addEventListener("click", () => goTo(i));
        dots.appendChild(dot);
    });
    section.hidden = false;

    let current = 0;

    function goTo(index) {
        const target = Math.max(0, Math.min(slides.length - 1, index));
        track.scrollTo({ left: target * track.clientWidth, behavior: "smooth" });
    }

    function update() {
        current = Math.round(track.scrollLeft / Math.max(track.clientWidth, 1));
        counter.textContent = `${current + 1} / ${slides.length}`;
        prev.disabled = current === 0;
        next.disabled = current === slides.length - 1;
        Array.from(dots.children).forEach((dot, i) => {
            dot.classList.toggle("active", i === current);
            dot.setAttribute("aria-current", i === current ? "true" : "false");
        });
    }

    prev.onclick = () => goTo(current - 1);
    next.onclick = () => goTo(current + 1);
    track.addEventListener("scroll", () => window.requestAnimationFrame(update), { passive: true });
    track.addEventListener("keydown", e => {
        if (e.key === "ArrowLeft") goTo(current - 1);
        if (e.key === "ArrowRight") goTo(current + 1);
    });
    window.addEventListener("resize", () => goTo(current));

    const controls = section.querySelector(".gallery-controls");
    controls.hidden = slides.length < 2;
    dots.hidden = slides.length < 2;
    update();
}

function textLink(text, url) {
    const a = document.createElement("a");
    a.href = url;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    a.textContent = text;
    return a;
}

function makeSlide({ image, alt, title, credit, href }) {
    const slide = document.createElement("figure");
    slide.className = "gallery-slide";
    slide.setAttribute("role", "group");
    slide.setAttribute("aria-roledescription", "slide");

    const media = document.createElement(href ? "a" : "div");
    media.className = href ? "gallery-media is-video" : "gallery-media";
    if (href) {
        media.href = href;
        media.target = "_blank";
        media.rel = "noopener noreferrer";
        media.setAttribute("aria-label", `Watch "${title}" on YouTube`);
    }

    const img = document.createElement("img");
    img.src = image;
    img.alt = alt;
    img.loading = "lazy";
    media.appendChild(img);

    if (href) {
        const play = document.createElement("span");
        play.className = "gallery-play";
        play.setAttribute("aria-hidden", "true");
        play.textContent = "▶";
        media.appendChild(play);
    }

    const caption = document.createElement("figcaption");
    caption.className = "gallery-caption";

    const titleEl = document.createElement("strong");
    titleEl.textContent = title;

    const creditEl = document.createElement("span");
    creditEl.className = "gallery-credit";
    creditEl.append(href ? `${credit} · YouTube` : credit);

    caption.append(titleEl, creditEl);
    slide.append(media, caption);
    return slide;
}

